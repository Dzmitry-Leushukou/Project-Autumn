"""Синтетический профиль спроса для генератора демо-сетей.

morning=exp(-(mid-510)²/(2*75²)), evening=exp(-(mid-1080)²/(2*90²)).
multiplier=0.25+0.75*morning+0.9*evening; mid — минуты середины интервала.
Пики в 08:30 и 18:00, это допущение генератора, не наблюдения.
В конструкторе тот же профиль и его варианты реализованы в demand_profile.ts,
который выполняется в браузере. Этот модуль вызывается scripts/generate_demos.py.
"""

import math


def demand_multiplier(mid):
    return (
        0.25
        + 0.75 * math.exp(-((mid - 510) ** 2) / (2 * 75**2))
        + 0.9 * math.exp(-((mid - 1080) ** 2) / (2 * 90**2))
    )
